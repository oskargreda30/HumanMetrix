import { describe, it, expect, vi, beforeEach, afterEach } from 'vitest';

const mockCreate = vi.fn();
const mockUpdateWhere = vi.fn().mockResolvedValue(undefined);
const mockUpdateSet = vi.fn().mockReturnValue({ where: mockUpdateWhere });
const mockUpdate = vi.fn().mockReturnValue({ set: mockUpdateSet });
const mockOrderBy = vi.fn();
const mockFrom = vi.fn().mockReturnValue({ orderBy: mockOrderBy });
const mockSelect = vi.fn().mockReturnValue({ from: mockFrom });

vi.mock('openai', () => ({
  default: vi.fn().mockImplementation(() => ({
    chat: {
      completions: {
        create: mockCreate,
      },
    },
  })),
}));

vi.mock('../../server/db', () => ({
  db: {
    select: mockSelect,
    update: mockUpdate,
  },
}));

vi.mock('@shared/schema', () => ({
  jobRoles: {
    id: 'id',
    name: 'name',
    requiredSkillScores: 'requiredSkillScores',
  },
}));

vi.mock('drizzle-orm', () => ({
  eq: vi.fn((field: any, value: any) => ({ field, value })),
}));

function createValidOpenAIResult(roleNames: string[]) {
  return roleNames.map(name => ({
    roleName: name,
    seniority: 'mid',
    fitSkills: {
      'Resilience': 63,
      'High Agency': 67,
      'Growth Mindset': 61,
      'Empathy & Ethics': 58,
      'Interpersonal Agility': 66,
      'Intellectual Curiosity': 64,
    },
    aiReadinessSkills: {
      'Data Fluency': 71,
      'Domain Expertise': 69,
      'Technical Fundamentals': 73,
      'Creativity & Innovation': 62,
      'Collaboration & Communication': 68,
      'AI Literacy & Prompt Engineering': 74,
      'Adaptability & Continuous Learning': 67,
      'Responsible AI & Ethical Awareness': 59,
      'Critical Thinking & Problem-Solving': 72,
    },
    criticalSkills: [
      'Technical Fundamentals',
      'AI Literacy & Prompt Engineering',
      'Critical Thinking & Problem-Solving',
      'Data Fluency',
      'Domain Expertise',
      'High Agency',
    ],
    promptArchitectureScore: 66,
    aiqScore: 68,
  }));
}

describe('generateRoleRequirements script', () => {
  const originalArgv = process.argv;
  let exitCode: number | undefined;
  const mockExit = vi.spyOn(process, 'exit').mockImplementation(((code?: number) => {
    exitCode = code;
  }) as any);

  beforeEach(() => {
    vi.clearAllMocks();
    exitCode = undefined;
    process.argv = ['node', 'script.ts'];
  });

  afterEach(() => {
    process.argv = originalArgv;
  });

  function setupDbForRoles(roles: Array<{ id: number; name: string; rss?: any }>) {
    let callCount = 0;
    mockOrderBy.mockImplementation(() => {
      callCount++;
      if (callCount === 1) {
        return Promise.resolve(roles.map(r => ({ id: r.id, name: r.name })));
      }
      return Promise.resolve(roles.map(r => ({
        id: r.id,
        name: r.name,
        rss: r.rss || null,
      })));
    });
  }

  async function runScript() {
    vi.resetModules();
    await import('../../server/scripts/NEWrolefitscores/generateRoleRequirements');
    await new Promise(resolve => setTimeout(resolve, 100));
  }

  it('should process roles and update the database', async () => {
    setupDbForRoles([{ id: 1, name: 'Software Engineer' }]);

    const result = createValidOpenAIResult(['Software Engineer']);
    mockCreate.mockResolvedValue({
      choices: [{ message: { content: JSON.stringify(result) } }],
    });

    await runScript();

    expect(mockCreate).toHaveBeenCalledTimes(1);
    expect(mockUpdate).toHaveBeenCalled();
    expect(mockUpdateSet).toHaveBeenCalled();
    const savedData = mockUpdateSet.mock.calls[0][0];
    expect(savedData.requiredSkillScores).toBeDefined();
    expect(savedData.requiredSkillScores.fitSkills).toBeDefined();
    expect(savedData.requiredSkillScores.aiReadinessSkills).toBeDefined();
    expect(savedData.requiredSkillScores.generatedBy).toBe('NEWrolefitscores');
    expect(exitCode).toBe(0);
  });

  it('should handle empty OpenAI response content gracefully', async () => {
    setupDbForRoles([{ id: 1, name: 'Designer' }]);

    mockCreate.mockResolvedValue({
      choices: [{ message: { content: null } }],
    });

    await runScript();

    expect(mockUpdate).not.toHaveBeenCalled();
    expect(exitCode).toBe(0);
  });

  it('should strip code fences from OpenAI response', async () => {
    setupDbForRoles([{ id: 1, name: 'Data Analyst' }]);

    const result = createValidOpenAIResult(['Data Analyst']);
    const fenced = '```json\n' + JSON.stringify(result) + '\n```';
    mockCreate.mockResolvedValue({
      choices: [{ message: { content: fenced } }],
    });

    await runScript();

    expect(mockUpdate).toHaveBeenCalled();
    expect(exitCode).toBe(0);
  });

  it('should skip roles already generated by NEWrolefitscores', async () => {
    setupDbForRoles([
      { id: 1, name: 'Engineer', rss: { generatedBy: 'NEWrolefitscores' } },
    ]);

    await runScript();

    expect(mockCreate).not.toHaveBeenCalled();
    expect(exitCode).toBe(0);
  });

  it('should handle role not found in OpenAI response', async () => {
    setupDbForRoles([{ id: 1, name: 'Missing Role' }]);

    mockCreate.mockResolvedValue({
      choices: [{ message: { content: JSON.stringify([]) } }],
    });

    await runScript();

    expect(mockUpdate).not.toHaveBeenCalled();
    expect(exitCode).toBe(0);
  });

  it('should fix critical skill count when not exactly 6', async () => {
    setupDbForRoles([{ id: 1, name: 'PM' }]);

    const result = createValidOpenAIResult(['PM']);
    result[0].criticalSkills = ['Resilience', 'High Agency'];
    mockCreate.mockResolvedValue({
      choices: [{ message: { content: JSON.stringify(result) } }],
    });

    await runScript();

    expect(mockUpdate).toHaveBeenCalled();
    const savedData = mockUpdateSet.mock.calls[0][0];
    const criticalCount = Object.values(savedData.requiredSkillScores.skillCriticality)
      .filter((v: any) => v === 'critical').length;
    expect(criticalCount).toBe(6);
    expect(exitCode).toBe(0);
  });

  it('should batch roles into groups of 15', async () => {
    const roles = Array.from({ length: 20 }, (_, i) => ({
      id: i + 1,
      name: `Role ${i + 1}`,
    }));
    setupDbForRoles(roles);

    mockCreate.mockImplementation(async (params: any) => {
      const prompt = params.messages[0].content;
      const roleLines = prompt.split('\n').filter((l: string) => /^\d+\.\s/.test(l));
      const names = roleLines.map((l: string) => l.replace(/^\d+\.\s/, ''));
      return {
        choices: [{ message: { content: JSON.stringify(createValidOpenAIResult(names)) } }],
      };
    });

    await runScript();

    expect(mockCreate).toHaveBeenCalledTimes(2);
    expect(exitCode).toBe(0);
  });

  it('should handle batch-level errors gracefully', async () => {
    setupDbForRoles([{ id: 1, name: 'Failing Role' }]);

    mockCreate.mockRejectedValue(new Error('API rate limit'));

    await runScript();

    expect(mockUpdate).not.toHaveBeenCalled();
    expect(exitCode).toBe(0);
  });
});
